"use client";

import { useEffect, useState } from "react";
import { useApp } from "./AppProvider";

type Lang = "en" | "hi";
type Result = { status: "loading" } | { status: "done"; text: string } | { status: "error"; message: string };

const SPEECH_LANG: Record<Lang, string> = { en: "en-IN", hi: "hi-IN" };

const COPY = {
  en: {
    open: "Summarize article", hint: "Short on time? Get the story in seconds.", head: "Quick summary", wait: "Summarizing the story…", tryAgain: "Try again",
    failed: "Couldn't summarize this story right now.", busy: "Too many requests. Please wait a minute and try again.",
    short: "This story is too short to summarize.", listen: "Listen", stop: "Stop", hide: "Hide summary",
    noVoice: "This device has no voice for this language.",
    note: "Summary generated by AI (Google Gemini). It can contain mistakes, so read the full story for details.",
  },
  hi: {
    open: "खबर का सारांश देखें", hint: "समय कम है? सेकंडों में पूरी बात जानें।", head: "संक्षेप में", wait: "सारांश तैयार हो रहा है…", tryAgain: "फिर कोशिश करें",
    failed: "अभी इस खबर का सारांश नहीं बन पाया।", busy: "बहुत ज़्यादा अनुरोध। एक मिनट बाद फिर कोशिश करें।",
    short: "यह खबर सारांश के लिए बहुत छोटी है।", listen: "सुनें", stop: "रोकें", hide: "सारांश छिपाएं",
    noVoice: "इस डिवाइस पर इस भाषा की आवाज़ उपलब्ध नहीं है।",
    note: "यह सारांश AI (Google Gemini) ने बनाया है। इसमें गलती हो सकती है, पूरी जानकारी के लिए पूरी खबर पढ़ें।",
  },
};

/** "Summarize article" button and the short AI summary it opens, in English or Hindi, which it can also read aloud. */
export default function ArticleSummary({ id }: { id: string }) {
  const { lang: siteLang } = useApp();
  const ui = COPY[siteLang === "hi" ? "hi" : "en"];
  const [open, setOpen] = useState(false);
  const [lang, setLang] = useState<Lang>(siteLang === "hi" ? "hi" : "en");
  const [results, setResults] = useState<Partial<Record<Lang, Result>>>({});
  const [speaking, setSpeaking] = useState(false);
  const [voiceNote, setVoiceNote] = useState(false);
  const [canSpeak, setCanSpeak] = useState(false);

  useEffect(() => {
    // only known in the browser; checked here so the server and first client render match
    setCanSpeak("speechSynthesis" in window);
    return () => { if ("speechSynthesis" in window) window.speechSynthesis.cancel(); };
  }, []);

  const stopSpeaking = () => {
    if ("speechSynthesis" in window) window.speechSynthesis.cancel();
    setSpeaking(false);
    setVoiceNote(false);
  };

  const load = async (l: Lang) => {
    setResults((r) => ({ ...r, [l]: { status: "loading" } }));
    let result: Result;
    try {
      const res = await fetch("/api/summary", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ id, lang: l }) });
      const data = await res.json().catch(() => ({}));
      if (res.ok && data.summary) result = { status: "done", text: data.summary };
      else result = { status: "error", message: res.status === 429 ? ui.busy : res.status === 422 ? ui.short : ui.failed };
    } catch {
      result = { status: "error", message: ui.failed };
    }
    setResults((r) => ({ ...r, [l]: result }));
  };

  const show = (l: Lang) => {
    stopSpeaking();
    setLang(l);
    setOpen(true);
    const known = results[l];
    if (!known || known.status === "error") load(l);
  };

  const close = () => {
    stopSpeaking();
    setOpen(false);
  };

  const current = results[lang];

  const toggleSpeech = () => {
    if (speaking) return stopSpeaking();
    if (current?.status !== "done") return;
    const voices = window.speechSynthesis.getVoices();
    const voice = voices.find((v) => v.lang.replace("_", "-").toLowerCase().startsWith(lang));
    // reading Hindi with an English voice comes out as noise, so say so instead
    if (voices.length > 0 && !voice) return setVoiceNote(true);
    const u = new SpeechSynthesisUtterance(current.text);
    u.lang = SPEECH_LANG[lang];
    if (voice) u.voice = voice;
    u.onend = () => setSpeaking(false);
    u.onerror = () => setSpeaking(false);
    window.speechSynthesis.cancel();
    window.speechSynthesis.speak(u);
    setVoiceNote(false);
    setSpeaking(true);
  };

  if (!open) {
    return (
      <div className="sum-cta">
        <button type="button" className="sum-open" onClick={() => show(lang)}>
          {ui.open}
        </button>
        <span className="sum-hint">{ui.hint}</span>
      </div>
    );
  }

  return (
    <section className="sum-box" aria-label={ui.head}>
      <div className="sum-head">
        <span className="sum-title">{ui.head}</span>
        <div className="sum-langs" role="group" aria-label="Summary language">
          <button type="button" className={lang === "en" ? "on" : ""} aria-pressed={lang === "en"} onClick={() => show("en")}>English</button>
          <button type="button" className={lang === "hi" ? "on" : ""} aria-pressed={lang === "hi"} onClick={() => show("hi")}>हिंदी</button>
        </div>
      </div>

      <div aria-live="polite">
        {current?.status === "loading" && <p className="sum-wait">{ui.wait}</p>}
        {current?.status === "error" && (
          <p className="sum-wait">{current.message} <button type="button" className="sum-link" onClick={() => load(lang)}>{ui.tryAgain}</button></p>
        )}
        {current?.status === "done" && <p className="sum-text" lang={lang}>{current.text}</p>}
      </div>
      {voiceNote && <p className="sum-note">{ui.noVoice}</p>}

      <div className="sum-foot">
        {current?.status === "done" && canSpeak && (
          <button type="button" className="sum-speak" onClick={toggleSpeech} aria-label={speaking ? ui.stop : ui.listen} title={speaking ? ui.stop : ui.listen}>
            {speaking ? (
              <svg viewBox="0 0 24 24" width="18" height="18" fill="currentColor" aria-hidden="true"><rect x="6" y="6" width="12" height="12" rx="2" /></svg>
            ) : (
              <svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                <path d="M11 5L6 9H3v6h3l5 4z" fill="currentColor" />
                <path d="M15.5 9.5a3.5 3.5 0 0 1 0 5" />
                <path d="M18.5 6.5a8 8 0 0 1 0 11" />
              </svg>
            )}
          </button>
        )}
        <button type="button" className="sum-link" onClick={close}>{ui.hide}</button>
      </div>
      <p className="sum-note">{ui.note}</p>
    </section>
  );
}
